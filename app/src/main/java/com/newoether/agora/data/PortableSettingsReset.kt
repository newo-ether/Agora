    prefs.remove(CUSTOM_MODELS)
    prefs.remove(ENABLED_MODELS)
    prefs.remove(ACTIVE_SYSTEM_PROMPT_ID)
    prefs.remove(MODEL_ALIASES_JSON)
    prefs[MODEL_PROVIDER_NAMES_JSON] = "{}"
