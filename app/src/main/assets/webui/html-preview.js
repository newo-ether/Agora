// The existing Markdown code leaf retains source/search ownership. This island owns preview UI.
import { render } from "./vendor/preact.mjs";
import { useLayoutEffect, useRef, useState } from "./vendor/preact-hooks.mjs";
import { html, useDialog } from "./html.js";
import { MoreMenu } from "./menu.js";
import { Spinner } from "./material/progress.js";
import { t } from "./i18n.js";
import { previewResourceSource } from "./html-preview-resources.js";
import { icon, ICON_CONTENT_COPY, ICON_DOWNLOAD, ICON_REFRESH, ICON_FULLSCREEN, ICON_CLOSE,
  ICON_MORE_VERT, ICON_CODE, ICON_PLAY_ARROW } from "./icons.js";

const MAX_SOURCE_CHARS = 512 * 1024;
const copy = source => navigator.clipboard?.writeText(source).catch(() => {});
function save(source) {
  const url = URL.createObjectURL(new Blob([source], { type: "text/html;charset=utf-8" }));
  const link = document.createElement("a");
  link.href = url;
  link.download = "preview.html";
  link.click();
  // Browsers consume the URL asynchronously after the trusted download activation.
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
function Action({ label, path, onClick, primary = false, anchor }) {
  return html`<button class=${`code-copy html-action${primary ? " primary" : ""}`} type="button"
    ref=${anchor} aria-label=${label} title=${label} onClick=${onClick}>${icon(path)}</button>`;
}

/** A fresh response-header sandbox for every entry. No generated bytes before the trusted probe. */
function Viewport({ source, revision, reduceMotion }) {
  const host = useRef(null);
  const [status, setStatus] = useState("loading");
  const [active, setActive] = useState(false);
  useLayoutEffect(() => {
    let visible = false;
    const update = () => setActive(visible && document.visibilityState === "visible");
    const observer = new IntersectionObserver(entries => {
      visible = entries[0].isIntersecting;
      update();
    });
    observer.observe(host.current);
    document.addEventListener("visibilitychange", update);
    return () => { observer.disconnect(); document.removeEventListener("visibilitychange", update); };
  }, []);
  useLayoutEffect(() => {
    if (!active) return;
    const element = host.current;
    let disposed = false, posted = false, documentLoaded = false, failed = false;
    let release = () => {}, frame, timer;
    const abort = new AbortController();
    const fail = () => {
      if (disposed || failed) return;
      failed = true;
      clearTimeout(timer);
      frame?.remove(); release();
      setStatus("failed");
    };
    // First load is the receiver shell: post the source once. The next load is document.write
    // finishing and reveals the frame; any later navigation fails closed.
    const loaded = () => {
      if (disposed || failed) return;
      if (!posted) {
        posted = true;
        clearTimeout(timer);
        const prefix = new URL(frame.src).href.replace(/\/frame$/, "");
        frame.contentWindow.postMessage({ source: previewResourceSource(source, prefix) }, "*");
        timer = setTimeout(fail, 25000);
        return;
      }
      if (documentLoaded) { fail(); return; }
      documentLoaded = true;
      clearTimeout(timer);
      setStatus("ready");
    };
    setStatus("loading");
    const start = async () => {
      try {
        if (source.length > MAX_SOURCE_CHARS) throw new Error("Source limit");
        const response = await fetch("/api/html-preview", { method: "POST", credentials: "same-origin",
          headers: { "Content-Type": "application/json" }, body: "{}", signal: abort.signal });
        if (!response.ok) throw new Error("Preview admission failed");
        const { id } = await response.json();
        release = () => {
          fetch(`/api/html-preview?release=${encodeURIComponent(id)}`, { method: "POST", credentials: "same-origin",
            headers: { "Content-Type": "application/json" }, body: "{}", keepalive: true }).catch(() => {});
          release = () => {};
        };
        if (disposed) { release(); return; }
        frame = document.createElement("iframe");
        frame.sandbox = "allow-scripts";
        frame.referrerPolicy = "no-referrer";
        frame.title = t.htmlPreview;
        frame.className = "html-preview-frame";
        frame.src = `/html-preview/${id}/frame`;
        frame.addEventListener("load", loaded);
        frame.addEventListener("error", fail);
        timer = setTimeout(fail, 5000);
        element.append(frame);
      } catch { if (!disposed) fail(); }
    };
    start();
    return () => {
      disposed = true; abort.abort(); clearTimeout(timer);
      frame?.remove(); release();
    };
  }, [source, revision, active]);
  useLayoutEffect(() => {
    if (status === "ready") host.current.querySelector("iframe")?.classList.add("ready");
  }, [status]);
  return html`<div class=${`html-preview-viewport${reduceMotion ? " reduced-motion" : ""}`} ref=${host}>
    <div class=${`html-preview-status${status === "ready" ? " ready" : ""}`} role="status" aria-hidden=${status === "ready"}>
      ${status === "failed" ? t.htmlUnsupported : html`<${Spinner} /><span>${t.htmlLoading}</span>`}</div>
  </div>`;
}

function Fullscreen({ source, language, reduceMotion, onClose }) {
  const dialog = useRef(null);
  const [preview, setPreview] = useState(true);
  const [revision, setRevision] = useState(0);
  const close = useDialog(dialog, onClose);
  return html`<dialog ref=${dialog} class="tool-media-viewer html-preview-fullscreen" aria-label=${t.htmlPreview}
    onCancel=${event => { event.preventDefault(); close(); }}>
    <div class="code-block"><div class="code-header">
      <span class="code-language">${language.toUpperCase()}</span>
      <div class="html-actions">
        <${Action} label=${preview ? t.htmlSource : t.htmlPreview} path=${preview ? ICON_CODE : ICON_PLAY_ARROW}
          primary onClick=${() => setPreview(!preview)} />
        <${Action} label=${t.htmlReload} path=${ICON_REFRESH} onClick=${() => { setPreview(true); setRevision(revision + 1); }} />
        <${Action} label=${t.copy} path=${ICON_CONTENT_COPY} onClick=${() => copy(source)} />
        <${Action} label=${t.htmlSave} path=${ICON_DOWNLOAD} onClick=${() => save(source)} />
        <${Action} label=${t.close} path=${ICON_CLOSE} onClick=${close} />
      </div></div>
      ${preview ? html`<${Viewport} source=${source} revision=${revision} reduceMotion=${reduceMotion} />` : html`<pre><code>${source}</code></pre>`}
    </div></dialog>`;
}

function Controls({ block, source, language, reduceMotion, forceSource }) {
  const [preview, setPreview] = useState(language === "html-preview");
  const [revision, setRevision] = useState(0);
  const [fullscreen, setFullscreen] = useState(false);
  const [menu, setMenu] = useState(null);
  const anchor = useRef(null);
  const showingPreview = preview && !forceSource;
  useLayoutEffect(() => {
    block.querySelector("pre").hidden = showingPreview;
    return () => { block.querySelector("pre").hidden = false; };
  }, [showingPreview]);
  const reload = () => { setPreview(true); setRevision(revision + 1); };
  return html`<div class="code-header"><span class="code-language">${language.toUpperCase()}</span>
    <div class="html-actions">
      <${Action} label=${showingPreview ? t.htmlSource : t.htmlRun}
        path=${showingPreview ? ICON_CODE : ICON_PLAY_ARROW} primary onClick=${() => setPreview(!preview)} />
      <${Action} label=${t.copy} path=${ICON_CONTENT_COPY} onClick=${() => copy(source)} />
      <${Action} label=${t.htmlSave} path=${ICON_DOWNLOAD} onClick=${() => save(source)} />
      <${Action} label=${t.options} path=${ICON_MORE_VERT} anchor=${anchor} onClick=${() => setMenu({ expanded: true })} />
    </div></div>
    ${showingPreview && !fullscreen && html`<${Viewport} source=${source} revision=${revision} reduceMotion=${reduceMotion} />`}
    ${menu && html`<${MoreMenu} expanded=${menu.expanded} reduceMotion=${reduceMotion} anchor=${anchor}
      onClose=${() => setMenu({ expanded: false })} onExited=${() => { setMenu(null); anchor.current?.focus(); }}>
      <button class="dropdown-item" role="menuitem" onClick=${() => { reload(); setMenu({ expanded: false }); }}>
        ${icon(ICON_REFRESH)}<span>${t.htmlReload}</span></button>
      <button class="dropdown-item" role="menuitem" onClick=${() => { setFullscreen(true); setMenu({ expanded: false }); }}>
        ${icon(ICON_FULLSCREEN)}<span>${t.htmlFullscreen}</span></button>
    </${MoreMenu}>`}
    ${fullscreen && !forceSource && html`<${Fullscreen} source=${source} language=${language} reduceMotion=${reduceMotion} onClose=${() => setFullscreen(false)} />`}`;
}

export function mountHtmlPreview(block) {
  const header = document.createElement("div");
  header.className = "html-preview-host";
  block.querySelector(".code-header").replaceWith(header);
  const source = JSON.parse(block.dataset.htmlSource);
  const language = block.dataset.htmlLanguage;
  return {
    update: (reduceMotion, forceSource) => render(html`<${Controls} block=${block} source=${source}
      language=${language} reduceMotion=${reduceMotion} forceSource=${forceSource} />`, header),
    dispose: () => render(null, header),
  };
}
