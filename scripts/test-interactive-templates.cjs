/* Folder-backed setup through the real sandbox: no AI/network while choosing inputs. */
module.exports = async ({page,open,assert}) => {
  const fs = require('node:fs'), path = require('node:path');
  const template = JSON.parse(fs.readFileSync(path.join(__dirname,'../examples/interactive-templates/osce/osce.agora-template.json'),'utf8'));
  assert.equal(template.linkedSkill, undefined);
  assert.equal(template.resourceFiles.length, 0);
  assert.equal(template.sourceDirectory, null);
  assert.ok(template.sourceFolderId);
  assert.equal(template.sourceFilesAuto, true);
  const files = ['Medicine/Cardiology/Heart_failure.MD','Medicine/Cardiology/Acute coronary syndrome.md','Surgery/General Surgery/Appendicitis.md'];
  const references=files.map(file=>({path:file,label:file.split('/').at(-1).replace(/\.md$/i,'').replace(/[-_]/g,' '),categories:file.split('/').slice(0,-1)}));
  const answer = {...template.answer,jsExpressions:['globalThis.agoraReferences = '+JSON.stringify(references)+';', 'globalThis.agoraSourceFiles = '+JSON.stringify(files),...template.answer.jsExpressions]};
  const viewport = page.viewportSize();
  await page.setViewportSize({width:360,height:900});
  let frame = await open(answer,false,false,{eInkMode:true,fontScale:1});
  await frame.getByRole('button',{name:'Cardiology (Medicine)',exact:true}).waitFor();
  assert.equal(await frame.locator('body').evaluate(el=>el.scrollWidth<=el.clientWidth),true);
  const sends = () => page.evaluate(()=>window.nativeEvents.filter(e=>e.method==='sendPrompt'));
  assert.equal((await sends()).length,0);
  assert.deepEqual(await frame.locator('body').evaluate(()=>Websandbox.connection.remote.listReferenceFiles()),references);
  assert.equal(await frame.locator('body').evaluate(()=>typeof Websandbox.connection.remote.readFile),'function');
  assert.equal((await sends()).length,0);
  await frame.getByRole('button',{name:'Cardiology (Medicine)',exact:true}).click();
  await frame.getByRole('button',{name:'Heart failure',exact:true}).click();
  await frame.locator('#count').focus(); await frame.locator('#count').press('ArrowRight');
  assert.equal((await sends()).length,0);
  assert.equal(await frame.locator('#count-value').textContent(),'13');
  const report = path.join(__dirname,'../app/build/reports/interactive-templates');fs.mkdirSync(report,{recursive:true});
  assert.equal(await frame.locator('.condition[aria-pressed=true]').evaluate(el => getComputedStyle(el).backgroundColor),'rgb(0, 0, 0)');
  await page.screenshot({path:path.join(report,'folder-osce-eink.png'),fullPage:true});
  await frame.locator('#start').click();
  await page.waitForFunction(()=>window.nativeEvents.some(e=>e.method==='sendPrompt'));
  assert.equal((await sends()).length,1);
  assert.deepEqual((await sends())[0].value.sourceFiles,['Medicine/Cardiology/Heart_failure.MD']);
  assert.deepEqual(JSON.parse((await sends())[0].value.text),{subject:'Medicine',specialty:'Cardiology',condition:'Heart failure',questions:13});
  assert.ok(!(await sends())[0].value.text.includes('examiner.md'));
  assert.ok(!(await sends())[0].value.text.includes('Appendicitis'));
  assert.equal(await frame.locator('#start').isDisabled(),true);
  await page.setViewportSize({width:900,height:1000});
  frame=await open(answer,false,false,{eInkMode:false,fontScale:1});
  await frame.getByRole('button',{name:'General Surgery (Surgery)',exact:true}).click();
  await frame.getByRole('button',{name:'Appendicitis',exact:true}).click();
  assert.equal((await sends()).length,0);
  await frame.locator('main').evaluate(async () => {
    await Promise.all(document.getAnimations().filter(a => a.effect.getComputedTiming().iterations !== Infinity)
      .map(a => a.finished.catch(() => {})));
  });
  assert.equal(await frame.locator('.condition[aria-pressed=true]').evaluate(el => {
    const style = getComputedStyle(el); return style.color !== style.backgroundColor;
  }),true);
  await page.screenshot({path:path.join(report,'folder-osce-regular.png'),fullPage:true});
  const catalogue=JSON.parse(fs.readFileSync(path.join(__dirname,'../examples/interactive-templates/osce/catalogue.json'),'utf8'));
  const allPaths=Object.entries(catalogue).flatMap(([subject,groups])=>Object.entries(groups).flatMap(([specialty,topics])=>topics.map(topic=>subject+'/'+specialty+'/'+topic.title+'.md')));
  const fullAnswer={...template.answer,jsExpressions:['globalThis.agoraSourceFiles = '+JSON.stringify(allPaths),...template.answer.jsExpressions]};
  await page.setViewportSize({width:360,height:900});
  frame=await open(fullAnswer,false,false,{eInkMode:true,fontScale:1});
  assert.equal(await frame.locator('#categories h2').allTextContents().then(labels=>labels.join(',')),'Medicine,Surgery');
  assert.equal(await frame.locator('#categories button').count(),18);
  assert.equal(await frame.getByRole('button',{name:'Cardiology (Medicine)',exact:true}).locator('small').textContent(),'15');
  assert.equal((await sends()).length,0);
  await page.screenshot({path:path.join(report,'folder-osce-specialties-eink.png'),fullPage:true});
  frame=await open(fullAnswer,false,false,{eInkMode:false,fontScale:1});
  await frame.locator('main').evaluate(async()=>{await Promise.all(document.getAnimations().filter(a=>a.effect.getComputedTiming().iterations!==Infinity).map(a=>a.finished.catch(()=>{})));});
  await page.screenshot({path:path.join(report,'folder-osce-specialties-regular.png'),fullPage:true});
  const mixedPaths=['Cases/Overview.MD','Cases/Cardiology/Heart.md'];
  frame=await open({...template.answer,jsExpressions:['globalThis.agoraSourceFiles = '+JSON.stringify(mixedPaths),...template.answer.jsExpressions]},false,false,{eInkMode:true,fontScale:1});
  await frame.getByRole('button',{name:'Cases',exact:true}).click();
  await frame.getByRole('button',{name:'Overview',exact:true}).click();
  assert.equal(await frame.locator('#start').isDisabled(),false);
  assert.equal((await sends()).length,0);
  await frame.getByRole('button',{name:'Cardiology',exact:true}).click();
  await frame.getByRole('button',{name:'Heart',exact:true}).click();
  assert.equal((await sends()).length,0);
  const general={title:'Folder browser',description:'Any file',fallback:'Browse files',html:'<main><button id="browse">Browse</button><button id="send">Start</button><output id="value"></output></main>',jsFunctions: 'async function browse(){const api=Websandbox.connection.remote;const root=await api.listDirectory({path:""});const folder=root.entries.find(x=>x.directory);const nested=await api.listDirectory({path:folder.path});const text=await api.readTextFile({path:nested.entries[0].path});const binary=await api.readFile({path:"cover.png",encoding:"base64"});document.getElementById("value").textContent=JSON.parse(text).title+":"+binary;}',jsExpressions:['document.getElementById("browse").onclick=browse','document.getElementById("send").onclick=()=>Websandbox.connection.remote.sendPrompt({text:"Use these",sourceFiles:["Data/menu.json","cover.png"]})']};
  frame=await open(general,false,false,{eInkMode:true,fontScale:1});
  await frame.locator('#browse').click();
  await frame.locator('#value').filter({hasText:'Cases:AAH/'}).waitFor();
  assert.equal((await sends()).length,0);
  assert.deepEqual(await page.evaluate(()=>window.nativeEvents.filter(e=>['listDirectory','readTextFile','readFile'].includes(e.method)).map(e=>e.method)),['listDirectory','listDirectory','readTextFile','readFile']);
  await frame.locator('#send').click();
  await page.waitForFunction(()=>window.nativeEvents.some(e=>e.method==='sendPrompt'));
  assert.deepEqual((await sends())[0].value.sourceFiles,['Data/menu.json','cover.png']);
  const folderBrowser=JSON.parse(fs.readFileSync(path.join(__dirname,'../examples/interactive-templates/folder-browser/folder-browser.agora-template.json'),'utf8'));
  assert.equal(folderBrowser.sourceFilesAuto,false);
  frame=await open(folderBrowser.answer,false,false,{eInkMode:true,fontScale:1});
  await frame.getByRole('button',{name:'cover.png',exact:true}).click();
  await frame.getByRole('button',{name:'▸ Data',exact:true}).click();
  await frame.getByRole('button',{name:'menu.json',exact:true}).click();
  assert.equal((await sends()).length,0);
  await page.screenshot({path:path.join(report,'general-folder-browser-eink.png'),fullPage:true});
  await frame.locator('#start').click();
  await page.waitForFunction(()=>window.nativeEvents.some(e=>e.method==='sendPrompt'));
  assert.deepEqual((await sends())[0].value.sourceFiles,['cover.png','Data/menu.json']);
  const review=JSON.parse(fs.readFileSync(path.join(__dirname,'../examples/interactive-templates/osce/review.agora-template.json'),'utf8'));
  frame=await open({...review.answer,jsExpressions:['globalThis.agoraWorkflowInput="Review outcome"',...review.answer.jsExpressions]},false,false,{eInkMode:true,fontScale:1});
  assert.equal(await frame.locator('#outcome').textContent(),'Review outcome');
  await frame.locator('#focus').fill('Heart failure assessment');
  assert.equal((await sends()).length,0);
  await frame.locator('#continue').click();
  await page.waitForFunction(()=>window.nativeEvents.some(e=>e.method==='sendPrompt'));
  assert.deepEqual(JSON.parse((await sends())[0].value),{focus:'Heart failure assessment'});
  await page.setViewportSize(viewport);
};
